"use client";

import { useEffect, useState } from "react";

export const OPEN_HELP_EVENT = "trustmind:open-help";

export function openHelpPanel() {
  if (typeof window !== "undefined") {
    window.dispatchEvent(new Event(OPEN_HELP_EVENT));
  }
}

const CRISIS_LINES = [
  { name: "Samaritans", detail: "Call 116 123 (free, 24/7)", href: "tel:116123" },
  {
    name: "NHS 111",
    detail: "Option 2 for urgent mental health support in England",
    href: "tel:111",
  },
  { name: "Emergency", detail: "Call 999 if you or someone else is in immediate danger", href: "tel:999" },
  {
    name: "Bristol Mindline",
    detail: "0117 203 4419 · Wed–Sun 7pm–11pm",
    href: "tel:01172034419",
  },
  { name: "Childline", detail: "0800 1111", href: "tel:08001111" },
  {
    name: "Papyrus HOPELINEUK",
    detail: "0800 068 4141",
    href: "tel:08000684141",
  },
] as const;

export function HelpChrome() {
  const [open, setOpen] = useState(false);

  useEffect(() => {
    function onOpen() {
      setOpen(true);
    }
    window.addEventListener(OPEN_HELP_EVENT, onOpen);
    return () => window.removeEventListener(OPEN_HELP_EVENT, onOpen);
  }, []);

  return (
    <>
      <button
        type="button"
        onClick={() => setOpen(true)}
        className="fixed bottom-4 right-4 z-[60] inline-flex items-center rounded-full bg-rose-700 px-4 py-2.5 text-sm font-semibold text-white shadow-lg shadow-rose-900/30 hover:bg-rose-800 sm:hidden"
      >
        Get help now
      </button>

      {open ? (
        <div
          className="fixed inset-0 z-[70] flex items-end justify-center bg-stone-950/50 p-4 sm:items-center"
          role="dialog"
          aria-modal="true"
          aria-labelledby="crisis-panel-title"
        >
          <div className="w-full max-w-lg rounded-3xl border border-rose-200 bg-[var(--surface)] p-6 shadow-2xl dark:border-rose-900">
            <div className="flex items-start justify-between gap-3">
              <div>
                <h2
                  id="crisis-panel-title"
                  className="font-display text-2xl text-stone-900 dark:text-stone-50"
                >
                  Get help now
                </h2>
                <p className="mt-1 text-sm text-stone-600 dark:text-stone-400">
                  If you are in danger, call 999. These numbers are UK support
                  lines — they are not generated by the model.
                </p>
              </div>
              <button
                type="button"
                onClick={() => setOpen(false)}
                className="rounded-lg px-2 py-1 text-sm text-stone-500 hover:bg-stone-100 dark:hover:bg-stone-800"
              >
                Close
              </button>
            </div>
            <ul className="mt-4 space-y-2">
              {CRISIS_LINES.map((line) => (
                <li key={line.name}>
                  <a
                    href={line.href}
                    className="block rounded-2xl border border-[var(--line)] px-4 py-3 hover:border-rose-300 hover:bg-rose-50 dark:hover:bg-rose-950/40"
                  >
                    <p className="text-sm font-semibold text-stone-900 dark:text-stone-100">
                      {line.name}
                    </p>
                    <p className="text-sm text-stone-600 dark:text-stone-400">
                      {line.detail}
                    </p>
                  </a>
                </li>
              ))}
            </ul>
          </div>
        </div>
      ) : null}
    </>
  );
}
