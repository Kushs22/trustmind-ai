"use client";

import { useEffect, useState } from "react";

export const OPEN_HELP_EVENT = "trustmind:open-help";

export function openHelpPanel() {
  if (typeof window !== "undefined") {
    window.dispatchEvent(new Event(OPEN_HELP_EVENT));
  }
}

const CRISIS_LINES = [
  { name: "Samaritans", detail: "Call 116 123 (free, 24/7)", href: "tel:116123" },
  {
    name: "NHS 111",
    detail: "Option 2 for urgent mental health support in England",
    href: "tel:111",
  },
  { name: "Emergency", detail: "Call 999 if you or someone else is in immediate danger", href: "tel:999" },
  {
    name: "Bristol Mindline",
    detail: "0117 203 4419 · Wed–Sun 7pm–11pm",
    href: "tel:01172034419",
  },
  { name: "Childline", detail: "0800 1111", href: "tel:08001111" },
  {
    name: "Papyrus HOPELINEUK",
    detail: "0800 068 4141",
    href: "tel:08000684141",
  },
] as const;

export function HelpChrome() {
  const [open, setOpen] = useState(false);

  useEffect(() => {
    function onOpen() {
      setOpen(true);
    }
    window.addEventListener(OPEN_HELP_EVENT, onOpen);
    return () => window.removeEventListener(OPEN_HELP_EVENT, onOpen);
  }, []);

  return (
    <>
      <button
        type="button"
        onClick={() => setOpen(true)}
        className="btn-crisis fixed z-[200] md:top-3.5 md:right-6 bottom-4 left-4 right-4 md:left-auto md:bottom-auto h-12 md:h-9 w-auto"
      >
        Get help now
      </button>

      {open ? (
        <div
          className="fixed inset-0 z-[210] flex animate-fade-in items-end justify-center bg-black/45 p-4 sm:items-center"
          role="dialog"
          aria-modal="true"
          aria-labelledby="crisis-panel-title"
        >
          <div className="animate-scale-in w-full max-w-lg rounded-[var(--radius-lg)] border border-[var(--color-border)] bg-[var(--color-surface)] p-6 shadow-[var(--shadow-xl)]">
            <div className="flex items-start justify-between gap-3">
              <div>
                <h2 id="crisis-panel-title">Get help now</h2>
                <p className="mt-1 text-[var(--text-sm)] text-[var(--color-text-secondary)]">
                  If you are in danger, call 999. These numbers are UK support
                  lines — they are not generated by the model.
                </p>
              </div>
              <button
                type="button"
                onClick={() => setOpen(false)}
                className="btn-ghost min-h-11"
              >
                Close
              </button>
            </div>
            <ul className="mt-4 space-y-2">
              {CRISIS_LINES.map((line) => (
                <li key={line.name}>
                  <a
                    href={line.href}
                    className="block rounded-[var(--radius-md)] border border-[var(--color-border)] px-4 py-3 hover:border-[var(--color-crisis)]"
                  >
                    <p className="text-[14px] font-semibold">{line.name}</p>
                    <p className="text-[13px] text-[var(--color-text-muted)]">
                      {line.detail}
                    </p>
                  </a>
                </li>
              ))}
            </ul>
          </div>
        </div>
      ) : null}
    </>
  );
}
